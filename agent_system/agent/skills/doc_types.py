def keyword_hits(text: str, words: list[str]) -> int:
    low = text.lower()
    return sum(1 for w in words if w in low)


@dataclass
class Signal:
    """Тип, определённый по набору признаков, и обоснование — единый
    результат классификации для страницы PDF, листа Excel или раздела
    docx."""

    unit: str                      # номер страницы / имя листа / раздела
    doc_type: str
    confidence: float
    reasons: list[str] = field(default_factory=list)
    signals: dict[str, Any] = field(default_factory=dict)


def classify_signals(s: dict[str, Any]) -> tuple[str, float, list[str]]:
    """Единое дерево решений по признакам. Ожидаемые ключи (недостающие
    считаются нулём/False): chars, words, tables, vector_paths,
    image_area_ratio, landscape, max_font, median_font, bom_hits,
    invoice_hits, drawing_hits.

    Порядок правил важен: от самых специфичных (таблица, скан) к самым
    общим (проза, смесь) — иначе широкое правило перехватит частный случай.
    """
    g = lambda k, d=0: s.get(k, d)  # noqa: E731
    reasons: list[str] = []

    chars = g("chars")
    tables = g("tables")
    vector_paths = g("vector_paths")
    image_area_ratio = g("image_area_ratio", 0.0)
    words = g("words")
    landscape = g("landscape", False)
    max_font = g("max_font", 0.0)
    median_font = g("median_font", 0.0)
    bom_hits = g("bom_hits")
    invoice_hits = g("invoice_hits")
    drawing_hits = g("drawing_hits")

    # 1. Пусто — дальше можно не разбираться.
    if chars == 0 and image_area_ratio < 0.05 and vector_paths == 0 and tables == 0:
        return "blank_page", 0.95, ["нет текста, картинок, графики и таблиц"]

    # 2. Скан: текстового слоя почти нет, страница занята растром.
    if chars < 30 and image_area_ratio > 0.5:
        reasons.append(f"текста {chars} симв., картинка {image_area_ratio:.0%} площади")
        return "scanned_image", 0.85, reasons

    # 3. Таблица есть — различаем BOM и счёт по ключевым словам.
    if tables > 0:
        if invoice_hits > bom_hits and invoice_hits > 0:
            reasons.append(f"таблица + финансовые термины ({invoice_hits})")
            return "invoice_financial", 0.8, reasons
        if bom_hits > 0:
            reasons.append(f"таблица + термины спецификации ({bom_hits})")
            return "bom_table", 0.85, reasons
        reasons.append("таблица есть, но тип содержимого не опознан по терминам")
        return "bom_table", 0.5, reasons

    # 4. Чертёж: много векторных линий + характерные термины основной надписи.
    if vector_paths >= 10 and (drawing_hits > 0 or chars < 400):
        reasons.append(f"{vector_paths} векторных элементов"
                       + (f", термины чертежа ({drawing_hits})"
                          if drawing_hits else ", текста мало"))
        return "technical_drawing", 0.75, reasons

    # 5. Слайд: альбомная ориентация, мало слов, заголовок заметно крупнее тела.
    title_ratio = (max_font / median_font) if median_font else 0
    if landscape and words <= 90 and title_ratio >= 1.3:
        reasons.append(f"альбомная ориентация, {words} слов, "
                       f"заголовок в {title_ratio:.1f}x крупнее текста")
        return "presentation_slide", 0.7, reasons

    # 6. Связный текст: много символов, векторной графики нет.
    if chars > 250 and vector_paths < 10:
        reasons.append(f"{chars} символов связного текста, графики нет")
        return "prose_text", 0.75, reasons

    reasons.append("признаки не дотягивают ни до одного профиля уверенно")
    return "mixed_report", 0.3, reasons



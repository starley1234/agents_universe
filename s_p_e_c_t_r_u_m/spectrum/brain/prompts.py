"""Системные промпты для RAG и агента S.P.E.C.T.R.U.M."""

from __future__ import annotations


class SystemPrompts:
    """Коллекция промптов для различных сценариев."""

    @staticmethod
    def rag_system() -> str:
        """Базовый системный промпт для RAG-ответов."""
        return (
            "Ты — интеллектуальный ассистент S.P.E.C.T.R.U.M. (Semantic Processing & Extraction Cluster).\n"
            "Твоя задача — отвечать на вопросы пользователя, основываясь ИСКЛЮЧИТЕЛЬНО на предоставленном контексте.\n\n"
            "ПРАВИЛА:\n"
            "1. Отвечай ТОЛЬКО на основе предоставленного контекста. Если информации недостаточно — скажи об этом.\n"
            "2. ВСЕГДА указывай источники информации: название файла, номер страницы, лист.\n"
            "3. Если данные противоречивы — укажи все варианты с источниками.\n"
            "4. Для числовых данных — приводи точные значения с единицами измерения.\n"
            "5. Отвечай на том языке, на котором задан вопрос.\n"
            "6. Структурируй ответ: используй списки, таблицы, заголовки для читаемости.\n"
        )

    @staticmethod
    def rag_with_context(question: str, context: str) -> str:
        """Формирует полный промпт для RAG с контекстом."""
        return (
            f"## КОНТЕКСТ (извлечённый из документов):\n\n{context}\n\n"
            f"## ВОПРОС ПОЛЬЗОВАТЕЛЯ:\n\n{question}\n\n"
            "Ответь на вопрос, используя ТОЛЬКО приведённый контекст. "
            "Укажи источники (файл, страница) для каждого утверждения."
        )

    @staticmethod
    def agent_system() -> str:
        """Системный промпт для автономного агента."""
        return (
            "Ты — автономный агент S.P.E.C.T.R.U.M., способный выполнять сложные задачи "
            "с использованием базы знаний и инструментов.\n\n"
            "ТВОИ ВОЗМОЖНОСТИ:\n"
            "- Поиск по семантической базе знаний (RAG)\n"
            "- Анализ конкретных документов\n"
            "- Извлечение структурированных данных из неструктурированных текстов\n"
            "- Формирование отчётов и сводок\n"
            "- Сравнение данных из разных источников\n\n"
            "ПРАВИЛА РАБОТЫ:\n"
            "1. Разбивай сложные задачи на шаги\n"
            "2. Всегда проверяй факты по первоисточникам\n"
            "3. Формируй структурированные результаты (таблицы, списки)\n"
            "4. Указывай степень уверенности в ответах\n"
            "5. Если задача не выполнима — объясни почему и предложи альтернативу\n"
        )

    @staticmethod
    def task_planning(task_description: str, available_sources: str) -> str:
        """Промпт для планирования задачи агентом."""
        return (
            f"## ЗАДАЧА:\n{task_description}\n\n"
            f"## ДОСТУПНЫЕ ИСТОЧНИКИ:\n{available_sources}\n\n"
            "Составь план выполнения задачи:\n"
            "1. Какие источники нужно проанализировать\n"
            "2. Какие данные извлечь из каждого\n"
            "3. Как структурировать итоговый результат\n"
            "4. Какие проверки выполнить\n"
        )

    @staticmethod
    def extraction_prompt(doc_type: str = "contract") -> str:
        """Промпт для структурированного извлечения данных."""
        prompts = {
            "contract": (
                "Извлеки из договора следующие поля:\n"
                "- Номер и дата договора\n"
                "- Стороны (названия, ИНН, ОГРН)\n"
                "- Предмет договора\n"
                "- Сумма и валюта\n"
                "- Сроки поставки/выполнения\n"
                "- Условия оплаты\n"
                "- Штрафные санкции\n"
                "- Срок действия\n"
                "Верни результат в JSON."
            ),
            "invoice": (
                "Извлеки из счёта/накладной:\n"
                "- Номер и дата\n"
                "- Поставщик и покупатель\n"
                "- Перечень товаров/услуг с количеством и ценами\n"
                "- Итоговая сумма, НДС\n"
                "Верни результат в JSON."
            ),
            "specification": (
                "Извлеки из технической спецификации:\n"
                "- Наименование изделия\n"
                "- Технические характеристики (параметр → значение)\n"
                "- Материалы и комплектующие\n"
                "- Требования к качеству\n"
                "- Габариты и масса\n"
                "Верни результат в JSON."
            ),
        }
        return prompts.get(doc_type, prompts["contract"])

    @staticmethod
    def comparison_prompt(items: str) -> str:
        """Промпт для сравнительного анализа."""
        return (
            f"На основе следующих данных:\n{items}\n\n"
            "Составь сравнительную таблицу. Выдели:\n"
            "- Общие параметры для сравнения\n"
            "- Преимущества и недостатки каждого варианта\n"
            "- Итоговую рекомендацию\n"
        )

    @staticmethod
    def summary_prompt(text: str, max_length: int = 500) -> str:
        """Промпт для суммаризации документа."""
        return (
            f"Суммаризируй следующий текст (максимум {max_length} слов):\n\n{text}\n\n"
            "Сохрани ключевые факты, цифры и имена. "
            "Укажи основные выводы и рекомендации."
        )

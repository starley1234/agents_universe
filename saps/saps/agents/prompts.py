def extract_json(text: str) -> Any:
    """Достать JSON из ответа модели, прощая типовое оформление.

    Модели регулярно оборачивают JSON в ```json, дописывают «Вот
    результат:» и ставят висящую запятую. Валить разбор из-за оформления
    расточительно — ответ уже оплачен.
    """
    if not text:
        return None
    candidates: list[str] = [m.group(1) for m in _JSON_FENCE.finditer(text)]
    candidates.extend(_balanced(text))
    for chunk in candidates:
        cleaned = _TRAILING_COMMA.sub(r"\1", chunk.strip())
        try:
            return json.loads(cleaned)
        except json.JSONDecodeError:
            continue
    return None


def _balanced(text: str) -> list[str]:
    """Верхнеуровневые {...} с учётом вложенности и строк."""
    out: list[str] = []
    depth, start, in_str, esc = 0, -1, False, False
    for i, ch in enumerate(text):
        if in_str:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                in_str = False
            continue
        if ch == '"':
            in_str = True
        elif ch == "{":
            if depth == 0:
                start = i
            depth += 1
        elif ch == "}" and depth > 0:
            depth -= 1
            if depth == 0 and start >= 0:
                out.append(text[start:i + 1])
                start = -1
    return out

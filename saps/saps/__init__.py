"""САПС — Система Агентской Поддержки Сертификации.

Интеллектуальный фронтенд к Teamcenter: берёт на себя грязную работу по
подготовке данных, чтобы в основную систему попадали только валидные и
готовые к проверке регулятором требования. САПС не заменяет Teamcenter
и не является системой управления требованиями — она их ГОТОВИТ.

ЧЕТЫРЕ АРХИТЕКТУРНЫХ ПРИНЦИПА (ТЗ п.2):

1. Hybrid Data Ingestion — два независимых источника: коннектор к
   Teamcenter SOA (ingest/teamcenter.py) и парсер отчуждаемых файлов
   Word/Excel (ingest/word.py, ingest/excel.py). Оба кладут данные в
   ОДИН staging-слой, поэтому дальнейший конвейер не знает и не должен
   знать, откуда пришло требование.
2. Agent-Based Core — агенты (agents/) независимы и общаются ТОЛЬКО
   через базу: агент читает требования, пишет находки, не вызывает
   другого агента напрямую. Нет «агента над агентами» — порядок задаёт
   человек или конвейер (тот же принцип, что в соседних проектах
   репозитория).
3. Database-First — PostgreSQL обязателен. Прослеживаемость
   (traceability) — не отчёт, а свойство схемы: у каждого требования
   есть источник, версия, история изменений и связь с доказательством.
4. Extensibility — плагины (plugins/) регистрируются в реестре и
   получают доступ к БД через тот же контракт, что и встроенные агенты.

ГЛАВНОЕ ПРАВИЛО ПРЕДМЕТНОЙ ОБЛАСТИ, определяющее весь код: РЕШЕНИЕ О
СООТВЕТСТВИИ ПРИНИМАЕТ ЧЕЛОВЕК. Ни один агент не имеет права записать
в Teamcenter изменение требования или проставить «соответствует» — он
готовит ПРЕДЛОЖЕНИЕ (suggestion), которое инженер видит как diff
«было/стало» и принимает или отклоняет (ТЗ п.6.2). Цена ошибки в
сертификации — не переписанный абзац, а недопуск воздушного судна к
эксплуатации.

Зависимости: psycopg (PostgreSQL) — обязательна; всё остальное, включая
разбор .docx/.xlsx и HTTP-сервер, работает на стандартной библиотеке.
"""

"""Кто берёт задачу: выбор профиля по её тексту.

Зачем. Чтобы запустить агента, надо было знать, какой из тринадцати
профилей подходит: `-P cad`, `-P office`, `-P ops`. Это знание о
внутреннем устройстве, которого у человека с задачей нет. Простой режим
снимает вопрос: пишешь задачу — система сама решает, кто начинает.

Почему правилами, а не моделью. Выбор должен быть ОБЪЯСНИМЫМ и
воспроизводимым: одинаковая задача обязана попадать к одному и тому же
агенту, а причина — печататься человеку. Лишний вызов модели ради
выбора роли ещё и стоит денег на каждом запуске. Правила проверяются
тестами; модель проверить нечем.

Когда правила молчат — так и говорим: «тема не распознана, взят общий
набор», а не подсовываем случайный профиль.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

#: Профиль -> (вес, признаки). Вес нужен, чтобы узкие темы побеждали
#: широкие: «отчёт» встречается везде, «openscad» — только в CAD.
#: Признаки пишутся ОСНОВАМИ слов: «шестер» ловит и «шестерня»,
#: и «шестерни», и «шестерённая» — падежи русского языка иначе съедают
#: половину совпадений. Основу берём ДО беглой гласной: после свёртки
#: «ё»→«е» слово «шестерённая» становится «шестеренная», и основа
#: «шестерн» в него уже не входит. Поймано тестом.
RULES: dict[str, list[tuple[float, str]]] = {
    "cad": [
        (3.0, r"openscad|\.scad|\bstl\b|\bcad\b"),
        (2.0, r"шестер|редуктор|водил|подшипник|вал\b|втулк|фланец"),
        (2.0, r"коллиз|пересечен[ии]е детал|габарит|водонепрониц"),
        (1.5, r"3d[- ]?модел|деталь|сборк|чертеж|допуск|зазор"),
    ],
    "coder": [
        (3.0, r"\bpython\b|\bjava|\bnode\b|\bsql\b|\.py\b|\.js\b|\.ts\b"),
        (2.0, r"напиши (код|скрипт|функци|программ)|отлад|дебаг|debug"),
        (2.0, r"падает тест|почини|исправ.{0,12}(ошибк|баг)|traceback"),
        (1.5, r"\bкод\b|функци|рефактор|скрипт|тест[ыа]?\b|библиотек"),
    ],
    "reviewer": [
        (3.0, r"провер[ьи].{0,20}код|ревью|review|код.?ревью"),
        (2.5, r"разбер[иь].{0,25}(что сделан|чужую работу|реализац)"),
        (2.0, r"замечани|найди (ошибк|недостатк)|критик"),
    ],
    "ops": [
        (3.0, r"systemctl|journalctl|\bdf -h\b|\bswap\b|\bdmesg\b"),
        (2.5, r"сервер|служб[аы]|демон|нагрузк|уронил|не запускается"),
        (2.0, r"(кончает|заканчивает|мало|нет).{0,15}(памят|мест|диск)"),
        (1.5, r"логи|диагност|тормозит|завис|потребление"),
    ],
    "office": [
        (3.0, r"\.docx|\.xlsx|\.pptx|презентац|слайд"),
        (2.5, r"(сдела|созда|подготов|офор).{0,25}(письм|документ|отчет|акт|справк|таблиц)"),
        (2.0, r"\bword\b|\bexcel\b|powerpoint|разошл|отправ.{0,10}(письм|почт)"),
        (1.5, r"телеграм|telegram|мессенджер|\bmax\b|рассыл"),
    ],
    "docs": [
        (3.0, r"\bpdf\b|скан|договор|накладн|счет-фактур"),
        (2.0, r"(разбер|извлек|вытащ|распозна).{0,20}(документ|файл|данн)"),
        (1.5, r"классифицир|реквизит|входящ.{0,10}документ"),
    ],
    "rag": [
        (3.0, r"проиндексир|индекс|база знаний|\brag\b"),
        (2.5, r"найди.{0,25}(в документ|в папк|в архив|среди файл)"),
        (2.0, r"поиск по (документ|файл|матери)"),
    ],
    "verify": [
        (3.0, r"верифиц|аудит|комплектност"),
        (2.5, r"провер.{0,25}(комплект|требован|соответств|на полнот)"),
        (2.0, r"соответств.{0,15}(гост|фап|норм|требован)"),
    ],
    "onto": [
        (3.0, r"онтолог|граф знаний|knowledge graph"),
        (2.0, r"связи между|модель предметной област"),
    ],
    "research": [
        # Изучение темы весит больше предметных слов: «обзор рынка
        # редукторов» — это исследование, а не работа с геометрией.
        # Без этого слово «редуктор» утаскивало задачу в CAD.
        (3.5, r"обзор рынка|собери информац|изучи рынок|что пишут"),
        (2.5, r"исследу|изучи\b|разузна|найди в интернет|погугли"),
        (2.5, r"сравн[иь].{0,25}(вариант|решени|подход|инструмент|модел)"),
        (1.5, r"\bобзор\b|что лучше|какие есть|подбери|аналог"),
    ],
    "marketing": [
        (2.5, r"реклам|продающ|лендинг|маркетинг"),
        (2.0, r"пост в|текст для (сайт|соцсет)|слоган|оффер"),
    ],
}

#: Задача выглядит долгой — берём автономный режим, а не одиночный запуск.
LONG_TASK = re.compile(
    r"(?i)(в течение|за ночь|несколько часов|автономн|сам[аоы]?стоятельн|"
    r"пока я|без меня|весь день|шаг за шагом|по этапам)")

#: Явное указание человека сильнее любых правил. Имя ловим ЛЮБЫМИ
#: буквами, а не только латиницей: человек напишет «[профиль: цад]»,
#: и такую опечатку надо не пропустить молча, а назвать.
EXPLICIT = re.compile(r"(?i)\[(профиль|profile)\s*[:= ]\s*([^\]]+)\]")


@dataclass
class Choice:
    profile: str | None          # None = общий набор, без профиля
    reason: str
    score: float
    autonomous: bool = False     # стоит ли предложить --auto
    runners_up: list[tuple[str, float]] = None  # type: ignore[assignment]

    def explain(self) -> str:
        head = (f"выбран профиль «{self.profile}»" if self.profile
                else "профиль не выбран, общий набор")
        tail = f" — {self.reason}"
        if self.runners_up:
            alt = ", ".join(f"{n} ({s:.1f})" for n, s in self.runners_up)
            tail += f"; ближайшие: {alt}"
        return head + tail


def _fold(text: str) -> str:
    """Привести к виду, по которому сравниваем.

    Буква «ё» пишется как придётся: «шестерённая» и «шестеренная» —
    одно слово, но регулярка с основой «шестерн» ловила только второе.
    Поймано тестом.
    """
    return (text or "").lower().replace("ё", "е")


def score_profiles(task: str) -> dict[str, float]:
    """Сколько баллов набрал каждый профиль. Отдельно — чтобы проверять."""
    t = _fold(task)
    out: dict[str, float] = {}
    for name, rules in RULES.items():
        total = 0.0
        for weight, pattern in rules:
            if re.search(pattern, t):
                total += weight
        if total:
            out[name] = round(total, 2)
    return out


def choose_profile(task: str, known: list[str] | None = None) -> Choice:
    """Кому отдать задачу. Правила, а не догадки: выбор объясняется.

    Порог 2.0 намеренно выше веса одиночного слабого признака: одно
    слово «отчёт» не должно уводить в делопроизводство задачу про
    редуктор. Не дотянули — честно берём общий набор.
    """
    text = task or ""
    m = EXPLICIT.search(_fold(text))
    if m:
        name = m.group(2).strip().lower()
        if known is None or name in known:
            return Choice(name, "указано явно в задаче", 99.0)
        # Опечался в имени — не повод бросать задачу: разбираем её
        # правилами, но об ошибке говорим вслух.
        fallback = choose_profile(EXPLICIT.sub(" ", _fold(text)), known)
        fallback.reason = (f"неизвестный профиль {name!r} в задаче; "
                           + fallback.reason)
        return fallback

    scores = score_profiles(text)
    if known:
        scores = {k: v for k, v in scores.items() if k in known}
    autonomous = bool(LONG_TASK.search(_fold(text)))

    if not scores:
        return Choice(None, "тема не распознана, взят общий набор", 0.0,
                      autonomous)

    ranked = sorted(scores.items(), key=lambda x: (-x[1], x[0]))
    best, top = ranked[0]
    if top < 2.0:
        return Choice(None,
                      f"признаков мало (лучший {best}: {top:.1f} из 2.0)",
                      top, autonomous)

    # Ничья — плохой знак: задача либо на стыке, либо размытая.
    if len(ranked) > 1 and abs(ranked[1][1] - top) < 0.5:
        return Choice(best,
                      f"признаки на стыке с «{ranked[1][0]}», взят {best}",
                      top, autonomous, ranked[1:3])

    why = f"совпали признаки темы (вес {top:.1f})"
    return Choice(best, why, top, autonomous, ranked[1:3])

"""AWOS — Agentic Workflow OS.

Среда, в которой живут и взаимодействуют агенты, — независимо от их
специализации. Это НЕ ещё один агент и НЕ библиотека промптов: здесь нет
знаний о предметной области, нет «умного» агента-руководителя и нет
зашитых ролей вроде «маркетолога». Есть операционная среда, которая
даёт четыре вещи, одинаковые для любого агента:

  1. Role-Based Collaboration — внутри ОДНОГО шага работают три роли:
     Исполнитель (делает), Критик (ищет дефекты), Контролёр (решает,
     принять или вернуть на доработку). Роли — контракт среды, а не
     свойство конкретного агента.
  2. Context Synchronization — общая доска (blackboard) на прогон:
     версионируемое, аудируемое пространство памяти, через которое
     агенты обмениваются данными, вместо склейки простыней текста.
  3. Human-in-the-Loop — точки контроля как ПЕРВОКЛАССНОЕ состояние
     прогона: `waiting_human` переживает перезапуск процесса, человек
     утверждает, отклоняет или правит результат, прогон продолжается
     с того же места.
  4. Tool Integration — инструменты как системные вызовы: внешние API,
     базы, файлы, shell. Доступ выдаётся по грантам (capability), любой
     вызов пишется в журнал.

ОТЛИЧИЕ ОТ СОСЕДЕЙ ПО РЕПОЗИТОРИЮ (общая философия — общий код НЕТ):
  * agent_system — один автономный агент с инструментами;
  * multi_agent_system_ontology (MAOS) — несколько агентов-личностей,
    семантический роутер, онтология в PostgreSQL+pgvector;
  * awos (этот проект) — САМА СРЕДА: детерминированное ядро, которое
    исполняет объявленные workflow, гоняет цикл качества, хранит
    состояние в SQLite и умеет останавливаться на человеке.

Зависимостей нет — только стандартная библиотека Python 3.10+.
"""
